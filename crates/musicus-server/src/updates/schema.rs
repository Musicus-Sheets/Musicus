//! The schema snapshot `crates/musicus-server/schema.sql` (a-db-check, R-OPS-038):
//! the structure of a database after all updates, as text that changes only
//! where the structure changes.
//!
//! [`snapshot`] reads `sqlite_master` of a database and writes every table,
//! virtual table, index, trigger and view as one block, sorted by table, then
//! kind (table, index, trigger), then name. The SQL is SQLite's own stored
//! text with comments removed and white space normalised; a table's columns
//! and constraints stand one per line, a trigger's statements too. Not
//! included: the runner's marker tables (they belong to the runner, not to an
//! update), the tables of the `sqlx::migrate!` time, SQLite's internal tables,
//! automatic indexes and the shadow tables of virtual tables.
//!
//! Generated by `scripts/db-schema.sh` (example `db_schema`, on a database
//! that `Db::open` created); `tests/updates.rs` fails when the file is out of date.

use sqlx::SqlitePool;

/// First lines of `schema.sql`.
pub const HEADER: &str = "\
-- Structure of a new Musicus database after all database updates (release updates and
-- previews), as the update runner creates it. Generated by scripts/db-schema.sh -- do not edit.
-- Comments and layout of the stored SQL are normalised. Not included: the runner's marker
-- tables (musicus_meta, musicus_updates, musicus_upgrades), SQLite's internal tables,
-- automatic indexes and the shadow tables of virtual tables.
";

/// The snapshot text of the database behind `pool`.
pub async fn snapshot(pool: &SqlitePool) -> Result<String, sqlx::Error> {
    let rows: Vec<(String, String, String, String)> = sqlx::query_as(
        "SELECT m.type, m.name, m.tbl_name, m.sql FROM sqlite_master m
         WHERE m.sql IS NOT NULL
           AND m.name NOT LIKE 'sqlite_%'
           AND m.tbl_name NOT IN ('musicus_meta', 'musicus_updates', 'musicus_upgrades', '_sqlx_migrations')
           AND m.name NOT IN (SELECT t.name FROM pragma_table_list t WHERE t.schema = 'main' AND t.type = 'shadow')",
    )
    .fetch_all(pool)
    .await?;
    Ok(render(rows))
}

fn rank(kind: &str) -> u8 {
    match kind {
        "table" | "view" => 0,
        "index" => 1,
        _ => 2,
    }
}

/// `rows`: (type, name, tbl_name, sql) from `sqlite_master`.
fn render(mut rows: Vec<(String, String, String, String)>) -> String {
    rows.sort_by(|a, b| (&a.2, rank(&a.0), &a.1).cmp(&(&b.2, rank(&b.0), &b.1)));
    let mut out = String::from(HEADER);
    for (kind, _, _, sql) in &rows {
        out.push('\n');
        out.push_str(&format_object(kind, sql));
        out.push_str(";\n");
    }
    out
}

#[derive(Debug, PartialEq)]
struct Token<'a> {
    text: &'a str,
    /// White space or a comment stood before it.
    space: bool,
}

/// Splits SQL into words, literals (strings, quoted names) and the
/// punctuation `(` `)` `,` `;`; comments count as white space.
fn tokens(sql: &str) -> Vec<Token<'_>> {
    let b = sql.as_bytes();
    let mut out = Vec::new();
    let (mut i, mut space) = (0, false);
    while i < b.len() {
        let c = b[i];
        if c.is_ascii_whitespace() {
            space = true;
            i += 1;
        } else if sql[i..].starts_with("--") {
            space = true;
            i = sql[i..].find('\n').map_or(b.len(), |n| i + n);
        } else if sql[i..].starts_with("/*") {
            space = true;
            i = sql[i + 2..].find("*/").map_or(b.len(), |n| i + 2 + n + 2);
        } else {
            let start = i;
            if matches!(c, b'(' | b')' | b',' | b';') {
                i += 1;
            } else {
                while i < b.len() {
                    let c = b[i];
                    if let Some(close) = match c {
                        b'\'' => Some(b'\''),
                        b'"' => Some(b'"'),
                        b'`' => Some(b'`'),
                        b'[' => Some(b']'),
                        _ => None,
                    } {
                        // A doubled closing quote is part of the literal.
                        i += 1;
                        while i < b.len() {
                            if b[i] == close {
                                if close != b']' && b.get(i + 1) == Some(&close) {
                                    i += 2;
                                    continue;
                                }
                                i += 1;
                                break;
                            }
                            i += 1;
                        }
                    } else if c.is_ascii_whitespace()
                        || matches!(c, b'(' | b')' | b',' | b';')
                        || sql[i..].starts_with("--")
                        || sql[i..].starts_with("/*")
                    {
                        break;
                    } else {
                        i += 1;
                    }
                }
            }
            out.push(Token { text: &sql[start..i], space });
            space = false;
        }
    }
    out
}

/// Tokens on one line: no space after `(` or before `)` and `,`, one after `,`.
fn join(tokens: &[Token<'_>]) -> String {
    let mut s = String::new();
    for (n, t) in tokens.iter().enumerate() {
        let prev = n.checked_sub(1).map(|p| tokens[p].text);
        let gap = match (prev, t.text) {
            (None, _) | (Some("("), _) | (_, ")" | "," | ";") => false,
            (Some(","), _) => true,
            _ => t.space,
        };
        if gap {
            s.push(' ');
        }
        s.push_str(t.text);
    }
    s
}

fn format_object(kind: &str, sql: &str) -> String {
    let mut t = tokens(sql);
    while t.last().is_some_and(|t| t.text == ";") {
        t.pop();
    }
    match kind {
        "table" => format_table(&t),
        "trigger" => format_trigger(&t),
        _ => join(&t),
    }
}

/// `CREATE [VIRTUAL] TABLE name (` + one item per line + `)` + rest (`STRICT`, …).
fn format_table(t: &[Token<'_>]) -> String {
    let Some(open) = t.iter().position(|t| t.text == "(") else { return join(t) };
    let (mut depth, mut items, mut start, mut close) = (0, Vec::new(), open + 1, None);
    for (i, tok) in t.iter().enumerate().skip(open) {
        match tok.text {
            "(" => depth += 1,
            ")" => {
                depth -= 1;
                if depth == 0 {
                    items.push(&t[start..i]);
                    close = Some(i);
                    break;
                }
            }
            "," if depth == 1 => {
                items.push(&t[start..i]);
                start = i + 1;
            }
            _ => {}
        }
    }
    let Some(close) = close else { return join(t) };
    let mut s = join(&t[..open]);
    s.push_str(" (\n");
    let lines: Vec<String> = items.iter().map(|item| format!("    {}", join(item))).collect();
    s.push_str(&lines.join(",\n"));
    s.push_str("\n)");
    let rest = join(&t[close + 1..]);
    if !rest.is_empty() {
        s.push(' ');
        s.push_str(&rest);
    }
    s
}

/// The head up to `BEGIN` on one line, each statement on its own line, `END`.
fn format_trigger(t: &[Token<'_>]) -> String {
    let Some(begin) = t.iter().position(|t| t.text.eq_ignore_ascii_case("BEGIN")) else { return join(t) };
    let mut s = join(&t[..=begin]);
    let mut start = begin + 1;
    for i in begin + 1..t.len() {
        if t[i].text == ";" {
            s.push_str("\n    ");
            s.push_str(&join(&t[start..=i]));
            start = i + 1;
        }
    }
    s.push('\n');
    s.push_str(&join(&t[start..]));
    s
}

#[cfg(test)]
mod tests {
    use super::*;

    fn row(kind: &str, name: &str, table: &str, sql: &str) -> (String, String, String, String) {
        (kind.into(), name.into(), table.into(), sql.into())
    }

    #[test]
    fn literals_and_comments() {
        let t = tokens("a 'it''s -- no' \"x \"\"y\"\"\" [b c] -- note\n/* c */ d(e,f);");
        let texts: Vec<_> = t.iter().map(|t| t.text).collect();
        assert_eq!(texts, ["a", "'it''s -- no'", "\"x \"\"y\"\"\"", "[b c]", "d", "(", "e", ",", "f", ")", ";"]);
        assert!(t[4].space && !t[5].space);
        assert_eq!(join(&t), "a 'it''s -- no' \"x \"\"y\"\"\" [b c] d(e, f);");
    }

    #[test]
    fn objects_are_sorted_and_laid_out() {
        let rows = vec![
            row(
                "trigger",
                "t_ins",
                "t",
                "CREATE TRIGGER t_ins AFTER INSERT ON t BEGIN\n  INSERT INTO u VALUES (new.id) ;\n  DELETE FROM u; END",
            ),
            row("index", "t_b", "t", "CREATE INDEX t_b ON t(b)"),
            row(
                "table",
                "t",
                "t",
                "CREATE TABLE t (\n  id INTEGER PRIMARY KEY, -- the key\n  b TEXT NOT NULL DEFAULT 'a, b' CHECK (b IN ('x','y')),\n  UNIQUE (id, b)\n) STRICT",
            ),
            row("table", "f", "f", "CREATE VIRTUAL TABLE f USING fts5(\n  title, tokenize = 'unicode61'\n)"),
            row("view", "a", "a", "CREATE VIEW a AS SELECT   1"),
        ];
        let text = render(rows);
        let body = text.strip_prefix(HEADER).unwrap();
        assert_eq!(
            body,
            "
CREATE VIEW a AS SELECT 1;

CREATE VIRTUAL TABLE f USING fts5 (
    title,
    tokenize = 'unicode61'
);

CREATE TABLE t (
    id INTEGER PRIMARY KEY,
    b TEXT NOT NULL DEFAULT 'a, b' CHECK (b IN ('x', 'y')),
    UNIQUE (id, b)
) STRICT;

CREATE INDEX t_b ON t(b);

CREATE TRIGGER t_ins AFTER INSERT ON t BEGIN
    INSERT INTO u VALUES (new.id);
    DELETE FROM u;
END;
"
        );
    }
}
