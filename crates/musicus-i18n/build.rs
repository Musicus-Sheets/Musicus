//! Generates `$OUT_DIR/messages.rs` from `locales/*/*.ftl` (d-i18n-fluent):
//! one typed function per English message in `t`, the catalogue sources of
//! every language, and the search tables `KEY_SPELLINGS` / `NAME_CONNECTORS`.
//! A syntax error, an attribute or a message without value fails the build.

#[path = "src/scan.rs"]
mod scan;

use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::path::Path;

/// The message whose literal words are the connecting words of part names.
const CONNECTOR_MESSAGE: &str = "part-name-with-key";
/// Prefix of the key names (`key-name-Bb`).
const KEY_NAME: &str = "key-name-";

fn main() {
    let dir = std::env::var("CARGO_MANIFEST_DIR").unwrap();
    let root = Path::new(&dir).join("locales");
    println!("cargo::rerun-if-changed=locales");
    println!("cargo::rerun-if-changed=src/scan.rs");

    let langs = scan::languages(&root);
    assert!(langs.first().is_some_and(|(l, _)| l == "en"), "locales/en is the source catalogue");
    let mut per_lang: Vec<(String, Vec<scan::Msg>)> = Vec::new();
    for (lang, files) in &langs {
        println!("cargo::rerun-if-changed=locales/{lang}");
        let mut all = Vec::new();
        for f in files {
            let msgs = scan::messages(f).unwrap_or_else(|e| panic!("{e}"));
            for m in &msgs {
                assert!(!m.has_attributes, "{lang}/{}: `{}` has attributes; use one message per text", m.file, m.id);
                assert!(m.has_value, "{lang}/{}: `{}` has no value", m.file, m.id);
                assert!(!all.iter().any(|x: &scan::Msg| x.id == m.id), "{lang}: `{}` defined twice", m.id);
            }
            all.extend(msgs);
        }
        per_lang.push((lang.clone(), all));
    }

    let mut out = String::from("// Generated by build.rs from locales/*/*.ftl. Do not edit.\n\n");

    // Shipped languages and their sources.
    let names: Vec<String> = langs.iter().map(|(l, _)| format!("{l:?}")).collect();
    writeln!(out, "/// Shipped languages (directories of `locales/`), English first.").unwrap();
    writeln!(out, "pub const LANGUAGES: &[&str] = &[{}];\n", names.join(", ")).unwrap();
    writeln!(out, "#[cfg(feature = \"bundles\")]\n#[allow(dead_code)]").unwrap();
    writeln!(out, "pub(crate) const SOURCES: &[(&str, &[&str])] = &[").unwrap();
    for (lang, files) in &langs {
        let incs: Vec<String> = files
            .iter()
            .map(|f| {
                let rel = f.strip_prefix(&dir).unwrap().to_string_lossy().replace('\\', "/");
                format!("include_str!(concat!(env!(\"CARGO_MANIFEST_DIR\"), \"/{rel}\"))")
            })
            .collect();
        writeln!(out, "    ({lang:?}, &[{}]),", incs.join(", ")).unwrap();
    }
    writeln!(out, "];\n").unwrap();

    let en = &per_lang[0].1;
    let ids: Vec<String> = en.iter().map(|m| format!("{:?}", m.id)).collect();
    writeln!(out, "/// Every message id of the English catalogue.").unwrap();
    writeln!(out, "pub const MESSAGE_IDS: &[&str] = &[{}];\n", ids.join(", ")).unwrap();

    // Search tables (all languages).
    let mut spellings: BTreeMap<String, Vec<String>> = BTreeMap::new();
    let mut connectors: Vec<String> = Vec::new();
    for (_, msgs) in &per_lang {
        for m in msgs {
            if let Some(code) = m.id.strip_prefix(KEY_NAME) {
                let s = m.literal.trim().to_owned();
                let list = spellings.entry(code.to_owned()).or_default();
                if !s.is_empty() && !list.contains(&s) {
                    list.push(s);
                }
            }
            if m.id == CONNECTOR_MESSAGE {
                for w in m.literal.split(|c: char| !c.is_alphanumeric()).filter(|w| !w.is_empty()) {
                    let w = w.to_lowercase();
                    if !connectors.contains(&w) {
                        connectors.push(w);
                    }
                }
            }
        }
    }
    writeln!(out, "/// Key code ⇒ its names in every shipped language (search aliases, a-client-part-names).").unwrap();
    writeln!(out, "pub const KEY_SPELLINGS: &[(&str, &[&str])] = &[").unwrap();
    for (code, list) in &spellings {
        writeln!(out, "    ({code:?}, &{list:?}),").unwrap();
    }
    writeln!(out, "];\n").unwrap();
    connectors.sort();
    writeln!(out, "/// Connecting words of derived part names in every shipped language, lower case.").unwrap();
    writeln!(out, "pub const NAME_CONNECTORS: &[&str] = &{connectors:?};\n").unwrap();

    // Typed functions.
    writeln!(out, "/// One function per English message (d-i18n-fluent, a-i18n-keys).").unwrap();
    writeln!(out, "#[cfg(feature = \"bundles\")]\n#[allow(non_snake_case, clippy::too_many_arguments, clippy::match_single_binding)]").unwrap();
    writeln!(out, "pub mod t {{\n    #[allow(unused_imports)]\n    use crate::{{Arg, message}};\n").unwrap();
    let mut keys: Vec<(String, String)> = Vec::new();
    for m in en {
        for line in m.text.lines() {
            writeln!(out, "    /// {}", line.replace("*/", "* /")).unwrap();
        }
        let name = scan::fn_name(&m.id);
        let params: Vec<String> = m.vars.iter().map(|v| format!("{}: impl Into<Arg>", scan::fn_name(v))).collect();
        let args: Vec<String> = m.vars.iter().map(|v| format!("({v:?}, {}.into())", scan::fn_name(v))).collect();
        writeln!(out, "    pub fn {name}({}) -> String {{", params.join(", ")).unwrap();
        writeln!(out, "        message({:?}, &[{}])\n    }}\n", m.id, args.join(", ")).unwrap();
        if let Some(code) = m.id.strip_prefix(KEY_NAME) {
            keys.push((code.to_owned(), m.id.clone()));
        }
    }
    writeln!(out, "    /// Name of a key code in the UI language (`key-name-<code>`), `None` for an unknown code.")
        .unwrap();
    writeln!(out, "    pub fn key_name(code: &str) -> Option<String> {{\n        match code {{").unwrap();
    for (code, id) in &keys {
        writeln!(out, "            {code:?} => Some(message({id:?}, &[])),").unwrap();
    }
    writeln!(out, "            _ => None,\n        }}\n    }}\n}}").unwrap();

    let dest = Path::new(&std::env::var("OUT_DIR").unwrap()).join("messages.rs");
    std::fs::write(dest, out).unwrap();
}
