#!/usr/bin/env python3
"""Side-by-side review of a translation (d-i18n-fluent): every message of the
English catalogue with its translator comment, the English and the translated
text, as a Markdown table on stdout. Not shipped; a review aid for the
maintainer (German is an agent draft that needs review, docs/agents/glossary.md).

Usage:
    python3 scripts/i18n-review.py [LANG] > review-de.md     # LANG defaults to de
    python3 scripts/i18n-review.py de --only-flagged         # missing or identical to English

Flags in the last column: `missing` (falls back to English, R-I18N-003),
`same` (identical to English: fine for "Import", "PDF", key names; check the rest).
"""

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent / "crates/musicus-i18n/locales"


def parse(path):
    """Messages of one .ftl file: id -> (comment, value). Simple line parser:
    a message starts in column 0 with `id =`, continuation lines are indented."""
    out, comment, cur = {}, [], None
    for line in path.read_text(encoding="utf-8").splitlines():
        if line.startswith("##"):
            comment, cur = [], None
        elif line.startswith("#"):
            comment.append(line.lstrip("# ").strip())
            cur = None
        elif line and not line[0].isspace() and "=" in line:
            mid, val = line.split("=", 1)
            cur = mid.strip()
            out[cur] = [" ".join(comment), val.strip()]
            comment = []
        elif cur and line.strip():
            out[cur][1] += "\n" + line.strip()
        elif not line.strip():
            cur = None
    return out


def cell(s):
    return s.replace("|", "\\|").replace("\n", "<br>") or " "


def main():
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    lang = args[0] if args else "de"
    only_flagged = "--only-flagged" in sys.argv
    files = sorted((ROOT / "en").glob("*.ftl"))
    total = missing = same = 0
    print(f"# Musicus UI messages: English | {lang}\n")
    print(f"Generated by `scripts/i18n-review.py {lang}` from `crates/musicus-i18n/locales`. "
          "Terminology: `docs/agents/glossary.md`.\n")
    for f in files:
        en = parse(f)
        tr_path = ROOT / lang / f.name
        tr = parse(tr_path) if tr_path.exists() else {}
        rows = []
        for mid, (comment, text) in en.items():
            total += 1
            got = tr.get(mid)
            flag = ""
            if got is None:
                flag, missing = "missing", missing + 1
            elif got[1] == text:
                flag, same = "same", same + 1
            if only_flagged and not flag:
                continue
            rows.append(f"| `{mid}` | {cell(comment)} | {cell(text)} | {cell(got[1] if got else '')} | {flag} |")
        if rows:
            print(f"\n## {f.name}\n")
            print(f"| Key | Note for translators | English | {lang} | Flag |")
            print("| --- | --- | --- | --- | --- |")
            print("\n".join(rows))
    print(f"\n{total} messages, {missing} missing, {same} identical to English.")


if __name__ == "__main__":
    main()
